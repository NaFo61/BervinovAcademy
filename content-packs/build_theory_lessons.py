def moves_add(n: int) -> list[int]:
    return [n + 1, n + 2, n * 2]


def moves_double(n: int) -> list[int]:
    return [n + 1, n * 2]


def moves_triple(n: int) -> list[int]:
    return [n + 1, n + 4, n * 3]


def classify(target: int, move_fn) -> tuple[list[int], list[int], list[int]]:
    window = range(1, target)
    win1 = [n for n in window if any(m >= target for m in move_fn(n))]
    win1_set = set(win1)
    lose = [
        n
        for n in window
        if n not in win1_set and all(m >= target or m in win1_set for m in move_fn(n))
    ]
    lose_set = set(lose)
    win2 = [n for n in window if n not in win1_set and any(m in lose_set for m in move_fn(n))]
    return win1, lose, win2


def position_table(target: int, move_fn, limit: int) -> str:
    win1, lose, win2 = classify(target, move_fn)
    rows = []
    for n in range(1, limit + 1):
        if n in win1:
            kind = "победа сразу"
        elif n in lose:
            kind = "проигрыш"
        elif n in win2:
            kind = "победа на втором ходу"
        else:
            kind = "не из этих трёх"
        steps = ", ".join(str(m) for m in move_fn(n))
        rows.append((n, steps, kind))
    return table(["камней S", "куда можно пойти", "что это значит"], rows, left={2})


