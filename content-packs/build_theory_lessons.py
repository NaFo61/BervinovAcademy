def table(headers: list[str], rows: list[tuple], left: set[int] | None = None) -> str:
    left = left or set()
    head = "".join(
        f'<th class="left">{cell}</th>' if index in left else f"<th>{cell}</th>"
        for index, cell in enumerate(headers)
    )
    body = []
    for row in rows:
        cells = []
        for index, cell in enumerate(row):
            cls = ' class="left"' if index in left else ""
            cells.append(f"<td{cls}>{cell}</td>")
        body.append("<tr>" + "".join(cells) + "</tr>")
    return '<table class="code-table"><tr>' + head + "</tr>" + "".join(body) + "</table>"


