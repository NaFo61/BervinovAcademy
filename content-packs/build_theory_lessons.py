def grid_dp(grid: list[list[int]], want_max: bool) -> list[list[int]]:
    rows = len(grid)
    cols = len(grid[0])
    dp = [[0] * cols for _ in range(rows)]
    dp[0][0] = grid[0][0]
    for col in range(1, cols):
        dp[0][col] = dp[0][col - 1] + grid[0][col]
    for row in range(1, rows):
        dp[row][0] = dp[row - 1][0] + grid[row][0]
        for col in range(1, cols):
            came = dp[row - 1][col] if want_max else dp[row - 1][col]
            left = dp[row][col - 1]
            best = max(came, left) if want_max else min(dp[row - 1][col], left)
            dp[row][col] = best + grid[row][col]
    return dp


def cells(grid: list[list[int]]) -> str:
    rows = []
    for row in grid:
        rows.append(tuple(row))
    width = len(grid[0])
    headers = [str(i + 1) for i in range(width)]
    return table([""] + headers, [(index + 1, *row) for index, row in enumerate(rows)])


