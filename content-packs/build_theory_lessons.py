def ways_to(goal: int, commands, ban: set[int] | None = None) -> list[int]:
    banned = ban or set()
    counts = [0] * (goal + 1)
    counts[1] = 0 if 1 in banned else 1
    for value in range(1, goal + 1):
        if value in banned or counts[value] == 0:
            continue
        for nxt in commands(value):
            if nxt <= goal and nxt not in banned:
                counts[nxt] += counts[value]
    return counts


def collect_paths(goal: int, steps: list[tuple[str, object]]) -> list[str]:
    found: list[str] = []

    def walk(value: int, text: str) -> None:
        if value == goal:
            found.append(text)
            return
        for label, fn in steps:
            nxt = fn(value)
            if nxt <= goal:
                walk(nxt, f"{text} —{label}→ {nxt}")

    walk(1, "1")
    return found


def path_lines(paths: list[str]) -> str:
    items = "".join(f"<li>{path}</li>" for path in paths)
    return "<ul>" + items + "</ul>"


