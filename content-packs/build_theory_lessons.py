def schedule(jobs: list[tuple[str, int, tuple[str, ...]]]) -> dict[str, tuple[int, int]]:
    finish: dict[str, int] = {}
    spans: dict[str, tuple[int, int]] = {}
    for name, duration, deps in jobs:
        start = 0 if not deps else max(finish[dep] for dep in deps)
        finish[name] = start + duration
        spans[name] = (start, finish[name])
    return spans


def span_table(spans: dict[str, tuple[int, int]], order: list[str]) -> str:
    rows = [(name, spans[name][0], spans[name][1], spans[name][1] - spans[name][0]) for name in order]
    return table(["процесс", "старт", "финиш", "сколько минут"], rows)


