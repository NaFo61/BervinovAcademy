def memoize(fn):
    cache: dict = {}

    def wrapped(n: int) -> int:
        if n not in cache:
            cache[n] = fn(n)
        return cache[n]

    return wrapped


@memoize
def sum_f(n: int) -> int:
    if n == 1:
        return 1
    return sum_f(n - 1) + n


@memoize
def gee(n: int) -> int:
    if n == 1:
        return 1
    if n == 2:
        return 2
    if n % 2:
        return gee(n - 1) - gee(n - 2)
    return gee(n - 1) + gee(n - 2)


@memoize
def ones(n: int) -> int:
    if n <= 1:
        return n
    if n % 2 == 0:
        return ones(n // 2)
    return ones(n - 1) + 1


@memoize
def fibish(n: int) -> int:
    if n < 3:
        return n
    return fibish(n - 1) + fibish(n - 2)


@memoize
def half_add(n: int) -> int:
    if n == 1:
        return 2
    if n % 2 == 0:
        return half_add(n // 2) + n
    return half_add(n - 1) + 1


